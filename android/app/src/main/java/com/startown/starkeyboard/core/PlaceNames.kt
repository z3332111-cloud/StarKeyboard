package com.startown.starkeyboard.core

/**
 * 地名：聯想（打完字後推薦下一個詞）不推薦地名；自己打注音時照常出現。
 * 字典是新聞語料，沒有詞性，所以用台灣縣市鄉鎮名單＋三字以上的地名結尾來判斷。和 iPhone 版 Core/Sources/KeyboardCore/PlaceNames.swift 是同一份。
 */
object PlaceNames {
    /** 兩個字也確定是地名的（台灣縣市、常見鄉鎮區、景點）；和一般詞同形的（中和、清水、大同、太平）不放 */
    val names: Set<String> = setOf(
        "台北", "臺北", "新北", "桃園", "台中", "臺中", "台南", "臺南", "高雄", "基隆", "新竹", "苗栗", "彰化", "南投",
        "雲林", "嘉義", "屏東", "宜蘭", "花蓮", "台東", "臺東", "澎湖", "金門", "馬祖", "連江",
        "淡水", "淡江", "板橋", "三重", "新莊", "新店", "土城", "蘆洲", "汐止", "樹林", "鶯歌", "三峽", "林口", "五股",
        "八里", "深坑", "石碇", "坪林", "三芝", "瑞芳", "烏來", "貢寮", "平溪", "士林", "北投", "內湖", "南港", "萬華",
        "中壢", "龜山", "八德", "大溪", "楊梅", "蘆竹", "大園", "龍潭", "竹北", "竹東", "頭份", "竹南", "豐原", "大甲",
        "沙鹿", "梧棲", "霧峰", "大里", "烏日", "員林", "鹿港", "斗六", "虎尾", "北港", "朴子", "新營", "永康", "安平",
        "麻豆", "鳳山", "岡山", "旗山", "美濃", "左營", "楠梓", "三民", "苓雅", "前鎮", "小港", "鼓山", "旗津", "恆春",
        "東港", "潮州", "羅東", "礁溪", "蘇澳", "頭城", "玉里", "綠島", "蘭嶼", "馬公", "墾丁", "九份", "阿里山", "日月潭",
        "淡水河", "淡水線"
    )

    /** 三個字以上、這些結尾的多半是地名或地方（淡水河、淡江大學、中山路） */
    val endings = listOf("市", "縣", "區", "鄉", "鎮", "村", "河", "溪", "江", "湖", "島", "港", "灣", "橋", "山", "路", "街", "線", "站", "大學", "公園", "機場", "車站", "夜市", "老街")

    fun isPlace(word: String): Boolean {
        if (word in names) return true
        if (names.any { word.length > it.length && word.startsWith(it) }) return true
        if (word.length < 3) return false
        return endings.any { word.endsWith(it) }
    }
}
