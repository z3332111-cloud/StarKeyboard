    /// 前面打的字結尾符合表裡的詞就給表情（長的詞優先），最多兩個
    static func after(_ text: String) -> [String] {
        let tail = text.trimmingCharacters(in: .whitespaces)
        guard !tail.isEmpty else { return [] }
        let hit = table.filter { tail.hasSuffix($0.0) }.max { $0.0.count < $1.0.count }
        return hit?.1 ?? []
    }
